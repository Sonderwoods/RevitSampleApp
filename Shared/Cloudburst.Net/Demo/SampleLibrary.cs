using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using System.Text.Json.Serialization;
using Cloudburst.Geometry;
using Cloudburst.Native;

namespace Cloudburst.Demo
{
    /// <summary>Sample project catalogue entry (shared with the web app; defined in cloudburst-core/src/samples.rs).</summary>
    public sealed class SampleInfo
    {
        [JsonPropertyName("id")] public string Id { get; set; }
        [JsonPropertyName("name")] public string Name { get; set; }
        [JsonPropertyName("description")] public string Description { get; set; }
        /// <summary>"synthetic" or "real".</summary>
        [JsonPropertyName("kind")] public string Kind { get; set; }
        [JsonPropertyName("rainPreset")] public int RainPreset { get; set; }
        /// <summary>EPSG:25832 [minx, miny, maxx, maxy] for real sites.</summary>
        [JsonPropertyName("bbox")] public double[] Bbox { get; set; }
        [JsonPropertyName("dhmFile")] public string DhmFile { get; set; }
        [JsonPropertyName("compareWith")] public string CompareWith { get; set; }
        public bool IsReal => Kind == "real";
        public override string ToString() => Name;
    }

    internal sealed class SampleJson
    {
        [JsonPropertyName("info")] public SampleInfo Info { get; set; }
        [JsonPropertyName("x0")] public double X0 { get; set; }
        [JsonPropertyName("y0")] public double Y0 { get; set; }
        [JsonPropertyName("step")] public double Step { get; set; }
        [JsonPropertyName("nx")] public int Nx { get; set; }
        [JsonPropertyName("ny")] public int Ny { get; set; }
        [JsonPropertyName("z")] public float[] Z { get; set; }
        [JsonPropertyName("buildings")] public List<Shape> Buildings { get; set; }
        [JsonPropertyName("surfaces")] public List<Shape> Surfaces { get; set; }
        [JsonPropertyName("kerbs")] public List<Shape> Kerbs { get; set; }
        internal sealed class Shape
        {
            [JsonPropertyName("name")] public string Name { get; set; }
            [JsonPropertyName("material")] public string Material { get; set; }
            [JsonPropertyName("xs")] public double[] Xs { get; set; }
            [JsonPropertyName("ys")] public double[] Ys { get; set; }
            [JsonPropertyName("height")] public double Height { get; set; }
        }
    }

    /// <summary>
    /// Sample projects for the "Load sample" picker: synthetic sites generated by the engine, and real Danish sites whose
    /// DHM terrain is fetched with tools/fetch_dhm.py (needs a Dataforsyningen token) into a samples folder.
    /// </summary>
    public static class SampleLibrary
    {
        /// <summary>Folders searched for real-site GeoTIFFs (plugin folder\samples, repo samples, Documents\Cloudburst\samples).</summary>
        public static List<string> SearchFolders { get; } = new List<string>
        {
            Path.Combine(Path.GetDirectoryName(typeof(SampleLibrary).Assembly.Location) ?? ".", "samples"),
            Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments), "Cloudburst", "samples"),
        };

        public static IReadOnlyList<SampleInfo> List()
        {
            var json = NativeMethods.TakeString(NativeMethods.cb_samples_json());
            return JsonSerializer.Deserialize<List<SampleInfo>>(json) ?? new List<SampleInfo>();
        }

        /// <summary>Path of the DHM GeoTIFF for a real site, or null if it hasn't been downloaded.</summary>
        public static string FindDhmFile(SampleInfo info)
        {
            if (info?.DhmFile == null) return null;
            return SearchFolders.Select(f => Path.Combine(f, info.DhmFile)).FirstOrDefault(File.Exists);
        }

        public static bool IsAvailable(SampleInfo info) => !info.IsReal || FindDhmFile(info) != null;

        /// <summary>Site model for a sample, in metres. Synthetic samples are placed at (offsetX, offsetY).
        /// Real sites use their DHM file in EPSG:25832 coordinates (Terrain mesh, no buildings — model them in the CAD app).</summary>
        public static SiteModel Load(string id, double offsetX = 0, double offsetY = 0, int realSiteStep = 2)
        {
            var info = List().FirstOrDefault(s => s.Id == id) ?? throw new ArgumentException($"Unknown sample '{id}'.");
            if (info.IsReal)
            {
                var f = FindDhmFile(info) ?? throw new FileNotFoundException(
                    $"Terrain for '{info.Name}' is not downloaded. Run tools/fetch_dhm.py --token <Dataforsyningen token> --site {info.Id} and put {info.DhmFile} in {SearchFolders[0]}.");
                var real = new SiteModel();
                real.Terrain.Add(Model.Engine.LoadTerrainRaster(f, realSiteStep));
                return real;
            }
            var p = NativeMethods.cb_sample_json(id);
            if (p == IntPtr.Zero) throw new InvalidOperationException(NativeMethods.LastError());
            var s = JsonSerializer.Deserialize<SampleJson>(NativeMethods.TakeString(p));
            var site = new SiteModel();
            var b = new TriangleMesh.Builder();
            for (int j = 0; j < s.Ny; j++)
                for (int i = 0; i < s.Nx; i++)
                    b.AddVertex(s.X0 + offsetX + i * s.Step, s.Y0 + offsetY + j * s.Step, s.Z[j * s.Nx + i]);
            for (int j = 0; j < s.Ny - 1; j++)
                for (int i = 0; i < s.Nx - 1; i++)
                {
                    int a = j * s.Nx + i;
                    b.AddQuad(a, a + 1, a + 1 + s.Nx, a + s.Nx);
                }
            site.Terrain.Add(b.Build("Terrain"));
            Polygon2 Poly(SampleJson.Shape sh) => new Polygon2(sh.Xs.Select(x => x + offsetX).ToArray(), sh.Ys.Select(y => y + offsetY).ToArray());
            foreach (var bl in s.Buildings) site.Buildings.Add(new BuildingInput { Footprint = Poly(bl), HeightAboveTerrain = bl.Height, Name = bl.Name });
            foreach (var su in s.Surfaces) site.Regions.Add(new MaterialRegion { Outline = Poly(su), MaterialId = su.Material });
            foreach (var k in s.Kerbs)
                site.Walls.Add(new WallLine { Line = new Polyline3(k.Xs.Select(x => x + offsetX).ToArray(), k.Ys.Select(y => y + offsetY).ToArray()), Height = k.Height });
            return site;
        }
    }
}
